def run():
    print("📡 LLMS_TXT_GENERATOR: Regenerating AI-interface files with live data...")
    s = get_state()
    print(f"  State: ${s['total_routed']:.4f} routed | {s['n_workers']} workers | {s['n_engines']} engines | {s['n_cycles']} cycles")

    # Generate docs/llms.txt
    llms_txt = generate_llms_txt(s)
    llms_file = DOCS / "llms.txt"
    llms_file.write_text(llms_txt, encoding="utf-8")
    print(f"  ✅ docs/llms.txt ({llms_file.stat().st_size:,} bytes, {llms_txt.count(chr(10))} lines)")

    # Generate docs/system-prompt-addition.txt
    spt = generate_system_prompt_addition(s)
    spt_file = DOCS / "system-prompt-addition.txt"
    spt_file.write_text(spt, encoding="utf-8")
    print(f"  ✅ docs/system-prompt-addition.txt ({len(spt)} chars)")

    # Generate docs/feed.json
    feed = generate_feed_json(s)
    feed_file = DOCS / "feed.json"
    feed_file.write_text(json.dumps(feed, indent=2, ensure_ascii=False), encoding="utf-8")
    print(f"  ✅ docs/feed.json ({feed_file.stat().st_size:,} bytes)")

    # Also trigger CONTEXT_PACKAGER if available
    try:
        import importlib.util
        spec = importlib.util.spec_from_file_location("CONTEXT_PACKAGER", "mycelium/CONTEXT_PACKAGER.py")
        if spec:
            cp = importlib.util.module_from_spec(spec)
            spec.loader.exec_module(cp)
            cp.run()
    except Exception as e:
        print(f"  [CONTEXT_PACKAGER] Skipped: {e}")

    if s["actions"]:
        print(f"\n  📋 {len(s['actions'])} human action(s) needed:")
        for a in s["actions"]:
            print(f"     • {a}")

    return {"status": "ok", "engines": s["n_engines"], "cycles": s["n_cycles"]}


if __name__ == "__main__":
    run()

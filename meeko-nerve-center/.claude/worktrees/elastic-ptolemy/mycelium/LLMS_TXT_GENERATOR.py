#!/usr/bin/env python3
"""
LLMS_TXT_GENERATOR.py — Keep docs/llms.txt Fresh With Real Data
=================================================================
Runs every hour inside GRAND_UNIFIED_LOOP.

The static docs/llms.txt was built once and will drift. This engine
reads all real state files and regenerates it with actual current numbers:
  - Total routed (real dollars, not $0.0000)
  - Workers registered (real count)
  - Pools (real balances)
  - Cycles run (real health data)
  - Pending human actions (dynamically detected from state)
  - Engine count (from mycelium directory)

Also regenerates docs/system-prompt-addition.txt and docs/feed.json
(the live state feed all AI agents can poll).

Writes: docs/llms.txt, docs/system-prompt-addition.txt, docs/feed.json
"""

import os
import json
import glob as _glob
from pathlib import Path
from datetime import datetime, timezone

DATA = Path("data")
DOCS = Path("docs")
MYCELIUM = Path("mycelium")
DATA.mkdir(exist_ok=True)
DOCS.mkdir(exist_ok=True)


def rj(path, default=None):
    try:
        return json.loads((DATA / path).read_text(encoding="utf-8"))
    except Exception:
        return default if default is not None else {}


def count_engines() -> int:
    """Count active Python engines in mycelium/."""
    try:
        py_files = list(MYCELIUM.glob("*.py"))
        # Exclude utility/helper files
        exclude = {"__init__", "conftest"}
        active = [f for f in py_files if f.stem not in exclude and not f.stem.startswith("LEGACY")]
        return len(active)
    except Exception:
        return 295  # fallback to known count


def get_state() -> dict:
    """Load all state files, return clean summary."""
    pool       = rj("pool_state.json")
    pools      = pool.get("pools", {})
    total_rout = pool.get("total_routed_usd", 0)
    workers    = rj("worker_registry.json")
    crisis     = rj("crisis_allocation.json")
    fd         = rj("first_dollar_state.json")
    health     = rj("health_log.json")
    legal      = rj("legal_status.json")
    overflow   = rj("overflow_events.json")
    alerts     = rj("alert_state.json")

    n_workers  = len(workers.get("workers", {}))
    n_overflow = len(overflow.get("overflow_events", []))
    health_pct = health.get("uptime_pct", 0)
    n_cycles   = health.get("cycles_total", 0)
    first_done = fd.get("happened", False)
    crisis_tot = (
        crisis.get("cumulative_total_usd", 0)
        or crisis.get("total_crisis_usd", 0)
        or 0
    )

    pool_balances = {
        k: pools.get(k, {}).get("balance_usd", 0)
        for k in ["crisis", "labor", "infrastructure", "growth"]
    }

    # Human actions still needed
    actions = []
    if not legal.get("opencollective_applied"):
        actions.append("Apply for Open Collective fiscal sponsorship (opencollective.com, 30 min)")
    if not legal.get("llc_formed"):
        actions.append("Form Ohio LLC ($99, enables bank account)")
    if not first_done:
        actions.append("Add GUMROAD_ACCESS_TOKEN to GitHub Secrets → 5 products go live")
    awesome = DATA / "grant_submissions" / "awesome_foundation_READY.md"
    if awesome.exists():
        actions.append("Submit Awesome Foundation $1,000 grant (file ready, awesomefoundation.org)")

    n_engines = count_engines()

    return {
        "n_engines": n_engines,
        "first_done": first_done,
        "total_routed": total_rout,
        "crisis_tot": crisis_tot,
        "n_workers": n_workers,
        "n_overflow": n_overflow,
        "health_pct": health_pct,
        "n_cycles": n_cycles,
        "pool_balances": pool_balances,
        "actions": actions,
        "n_alerts": alerts.get("total_alerts_sent", 0),
    }


